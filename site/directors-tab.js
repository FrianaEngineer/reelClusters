// Renders the "Explore Directors by Cluster" tab (site/movie-map.html) from
// window.FILMS + DirectorUtils (see site/assets/director-utils.js) +
// window.DIRECTOR_INFO (see site/assets/director-info.js).
(function () {
  "use strict";

  var index = window.DirectorUtils.buildIndex(window.FILMS);
  var foldForSearch = window.DirectorUtils.foldForSearch;
  var splitDirectors = window.DirectorUtils.splitDirectors;
  var slugify = window.DirectorUtils.slugify;
  var directorInfo = window.DIRECTOR_INFO || {};

  // Search matches on the director's first OR last name starting with what
  // was typed ("ch" -> Chaplin, Chahine... but not e.g. "Mizoguchi", which
  // merely contains "ch" mid-word) rather than a substring match anywhere in
  // the full name. Multi-word names (see "Carl Th. Dreyer", "Francis Ford
  // Coppola") only match on their first and last word, not any middle name
  // or initial. Built once here since it only depends on the director index,
  // not the cluster grid.
  var directorMatchInfo = Object.create(null);
  Object.keys(index.directors).forEach(function (slug) {
    var words = foldForSearch(index.directors[slug].name).split(/\s+/).filter(Boolean);
    directorMatchInfo[slug] = {
      first: words[0] || "",
      last: words[words.length - 1] || "",
    };
  });

  function prefixMatches(info, term) {
    return info.first.indexOf(term) === 0 || info.last.indexOf(term) === 0;
  }

  // Plain iterative Levenshtein (edit distance): how many single-character
  // insertions/deletions/substitutions turn `a` into `b`.
  function levenshtein(a, b) {
    var m = a.length, n = b.length;
    if (m === 0) return n;
    if (n === 0) return m;
    var prev = [];
    for (var j = 0; j <= n; j++) prev[j] = j;
    for (var i = 1; i <= m; i++) {
      var curr = [i];
      for (var j2 = 1; j2 <= n; j2++) {
        var cost = a.charAt(i - 1) === b.charAt(j2 - 1) ? 0 : 1;
        curr[j2] = Math.min(prev[j2] + 1, curr[j2 - 1] + 1, prev[j2 - 1] + cost);
      }
      prev = curr;
    }
    return prev[n];
  }

  // How many typo'd characters we're willing to tolerate, scaled to query
  // length -- short queries (under 3 chars) already get plenty of real
  // prefix matches, so fuzzy-matching them would just be noisy; longer
  // queries can tolerate a couple of slipped letters ("vlacill" -> Vláčil).
  function fuzzyThreshold(len) {
    if (len < 3) return 0;
    if (len < 6) return 1;
    return 2;
  }

  // Fallback for when the exact prefix search (above) finds nothing: finds
  // directors whose first or last name is a close-enough typo of what was
  // typed (e.g. "chalie" -> "Charles" Chaplin). Only returns the single
  // closest tier of matches, not everything within the threshold -- e.g. for
  // "berman" that means just Bergman/Shumlin (edit distance 1), not also a
  // dozen barely-related distance-2 names.
  function fuzzyMatchSlugs(term) {
    var threshold = fuzzyThreshold(term.length);
    if (threshold === 0) return null;

    var scored = [];
    Object.keys(directorMatchInfo).forEach(function (slug) {
      var info = directorMatchInfo[slug];
      var dist = Math.min(levenshtein(term, info.first), levenshtein(term, info.last));
      if (dist <= threshold) scored.push({ slug: slug, dist: dist });
    });
    if (!scored.length) return null;

    var minDist = scored.reduce(function (m, s) { return Math.min(m, s.dist); }, Infinity);
    var slugs = Object.create(null);
    scored.forEach(function (s) {
      if (s.dist === minDist) slugs[s.slug] = true;
    });
    return slugs;
  }

  // Restricts each cluster's card grid to the same names shown in that
  // cluster's "Top directors" table (site/clusters/<id>.html), generated by
  // src/build_site.py into window.TOP_DIRECTORS. A joint credit there (e.g.
  // "Michael Powell and Emeric Pressburger") is split so both individual
  // director cards stay in. Clusters absent from TOP_DIRECTORS (hiddenGems,
  // which has no "Top directors" table) keep their full director list.
  function topDirectorSlugs(clusterId) {
    var names = window.TOP_DIRECTORS && window.TOP_DIRECTORS[clusterId];
    if (!names) return null;
    var slugs = Object.create(null);
    names.forEach(function (raw) {
      splitDirectors(raw).forEach(function (name) {
        slugs[slugify(name)] = true;
      });
    });
    return slugs;
  }

  var clustersEl = document.getElementById("dir-clusters");
  var clusterTpl = document.getElementById("dir-cluster-template");
  var cardTpl = document.getElementById("dir-card-template");
  var searchInput = document.getElementById("dir-search");
  var searchStatus = document.getElementById("dir-search-status");
  var emptyEl = document.getElementById("dir-empty");
  var emptyTermEl = document.getElementById("dir-empty-term");

  var totalDirectors = Object.keys(index.directors).length;

  // Each cluster starts collapsed -- only its name + count is shown until
  // clicked. Searching temporarily force-expands any cluster with a match
  // (see applyFilter); this map is what's restored once the search is
  // cleared. A cluster named in the URL hash (e.g. a "View this cluster"
  // link from a director profile page) starts expanded instead.
  var initialHash = (window.location.hash || "").replace(/^#cluster-/, "");
  var manuallyExpanded = Object.create(null);

  function swatchStyle(color) {
    var style = "background:" + color;
    if (color && color.toLowerCase() === "#ffffff") {
      style += ";border:1px solid #5a5a5a";
    }
    return style;
  }

  function setExpanded(section, expanded) {
    var button = section.querySelector(".dir-cluster-toggle");
    var wrap = section.querySelector(".dir-grid-wrap");
    section.classList.toggle("is-expanded", expanded);
    button.setAttribute("aria-expanded", String(expanded));
    if (expanded) {
      wrap.removeAttribute("inert");
    } else {
      wrap.setAttribute("inert", "");
    }
  }

  function render() {
    var frag = document.createDocumentFragment();

    index.clusters.forEach(function (cluster) {
      var section = clusterTpl.content.firstElementChild.cloneNode(true);
      section.id = "cluster-" + cluster.id;
      section.style.setProperty("--cluster-color", cluster.color);

      var swatch = section.querySelector(".dir-cluster-swatch");
      swatch.setAttribute("style", swatchStyle(cluster.color));

      var topSlugs = topDirectorSlugs(cluster.id);
      var directorSlugs = topSlugs
        ? cluster.directorSlugs.filter(function (slug) { return topSlugs[slug]; })
        : cluster.directorSlugs;

      section.querySelector(".dir-cluster-name").textContent = cluster.name;
      var count = directorSlugs.length;
      section.querySelector(".dir-cluster-meta").textContent =
        count + (count === 1 ? " director" : " directors") + " · " +
        cluster.filmCount + (cluster.filmCount === 1 ? " film" : " films");

      var viewLink = section.querySelector(".dir-cluster-viewlink");
      if (cluster.page) {
        viewLink.href = cluster.page;
      } else {
        viewLink.remove();
      }

      var grid = section.querySelector(".dir-grid");
      directorSlugs.forEach(function (slug) {
        var director = index.directors[slug];
        var card = cardTpl.content.firstElementChild.cloneNode(true);
        var link = card.querySelector(".dir-card-link");
        link.href = "director.html?director=" + encodeURIComponent(slug);
        card.querySelector(".dir-card-name").textContent = director.name;
        card.dataset.slug = slug;
        var meta = directorInfo[slug];
        if (meta && meta.image && meta.imageAlt) {
          var avatarImg = card.querySelector(".dir-avatar img");
          avatarImg.src = meta.image;
          avatarImg.alt = meta.imageAlt;
        }
        grid.appendChild(card);
      });

      manuallyExpanded[cluster.id] = cluster.id === initialHash;
      setExpanded(section, manuallyExpanded[cluster.id]);

      section.querySelector(".dir-cluster-toggle").addEventListener("click", function () {
        manuallyExpanded[cluster.id] = !manuallyExpanded[cluster.id];
        setExpanded(section, manuallyExpanded[cluster.id] || isSearching());
      });

      frag.appendChild(section);
    });

    clustersEl.appendChild(frag);

    if (initialHash && document.getElementById("cluster-" + initialHash)) {
      document.getElementById("cluster-" + initialHash).scrollIntoView({ block: "start" });
    }
  }

  function isSearching() {
    return searchInput.value.trim().length > 0;
  }

  function applyFilter(rawTerm) {
    var term = foldForSearch(rawTerm.trim());
    var searching = term.length > 0;
    var allCards = clustersEl.querySelectorAll(".dir-card");
    var visibleDirectors = Object.create(null);
    var anyVisible = false;
    var isFuzzy = false;

    // Try exact first/last-name-prefix matching first; only fall back to
    // fuzzy (typo-tolerant) matching if that finds nobody at all, so a
    // query like "ch" -- which already matches plenty of real prefixes --
    // never gets diluted with loosely-similar fuzzy noise.
    var fuzzySlugs = null;
    if (term) {
      var anyPrefixMatch = Object.keys(directorMatchInfo).some(function (slug) {
        return prefixMatches(directorMatchInfo[slug], term);
      });
      if (!anyPrefixMatch) {
        fuzzySlugs = fuzzyMatchSlugs(term);
        isFuzzy = !!fuzzySlugs;
      }
    }

    allCards.forEach(function (card) {
      var matches;
      if (!term) {
        matches = true;
      } else if (fuzzySlugs) {
        matches = !!fuzzySlugs[card.dataset.slug];
      } else {
        matches = prefixMatches(directorMatchInfo[card.dataset.slug], term);
      }
      card.hidden = !matches;
      if (matches) {
        anyVisible = true;
        visibleDirectors[card.querySelector(".dir-card-name").textContent] = true;
      }
    });

    clustersEl.querySelectorAll(".dir-cluster").forEach(function (section) {
      var clusterId = section.id.replace(/^cluster-/, "");
      var visibleCount = section.querySelectorAll(".dir-card:not([hidden])").length;
      section.hidden = visibleCount === 0;
      setExpanded(section, searching ? visibleCount > 0 : manuallyExpanded[clusterId]);
    });

    if (!term) {
      searchStatus.textContent = totalDirectors + " directors across " + index.clusters.length + " clusters.";
      emptyEl.hidden = true;
    } else if (!anyVisible) {
      searchStatus.textContent = "";
      emptyEl.hidden = false;
      emptyTermEl.textContent = rawTerm.trim();
    } else {
      var n = Object.keys(visibleDirectors).length;
      if (isFuzzy) {
        searchStatus.textContent =
          "No exact match for “" + rawTerm.trim() + "” — showing " +
          n + (n === 1 ? " close match" : " close matches") + ".";
      } else {
        searchStatus.textContent = n + (n === 1 ? " director matches" : " directors match") + " “" + rawTerm.trim() + "”.";
      }
      emptyEl.hidden = true;
    }
  }

  render();
  applyFilter("");
  searchInput.addEventListener("input", function () {
    applyFilter(searchInput.value);
  });
})();
